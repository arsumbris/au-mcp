// Callable-result helpers.
//
// A callable returns the SDK's `CallableResult` ({ content, isError? }). `content`
// is the text payload; the MCP-server shim (Phase 5) formats it into MCP content.

import type { CallableResult } from '@arsumbris/au-mcp-sdk'

export const ok = (content: unknown): CallableResult => ({ content })
export const fail = (message: string): CallableResult => ({ content: `Error: ${message}`, isError: true })

/**
 * The engine-unreachable hint every read appends when the broker cannot be reached.
 * The agent sees this whenever the engine is down, so it is high-frequency agent-facing
 * text — ONE constant, not the eleven hand-copied sentences it replaced (which had already
 * drifted into three different wordings saying "vault", "workspace", and neither).
 *
 * "repo" is the ENTRY sense of the word: the daemon is started on ONE folder-repo directory
 * (`au daemon start <dir>`), not on the composed knowledge base it derives from that entry.
 */
export const ENGINE_DOWN_HINT = 'Is the daemon running on the repo? (the human starts it)'
/** `<what the broker threw>. <the hint>` — the shape an engine read's catch block returns. */
export const engineDown = (e: unknown): string => `${(e as Error).message}. ${ENGINE_DOWN_HINT}`

// --- input access ----------------------------------------------------------
// Tool input arrives as `unknown` over the wire. It is now SHAPE-VALIDATED before a
// plugin runs: the daemon validates it against `mcp.tool.<tool>` via the engine
// (gate-side, plan 5c.3), and the advertised JSON Schema is generated by au-type-codegen
// (5c.4). These accessors are the plugin's defensive reads of the validated input,
// not a second validator layer (no zod). (Both shipped: validate 5c.3, codegen 5c.4.)

const rec = (input: unknown): Record<string, unknown> =>
  input && typeof input === 'object' ? (input as Record<string, unknown>) : {}

export const optString = (input: unknown, key: string): string | undefined => {
  const v = rec(input)[key]
  return typeof v === 'string' ? v : undefined
}
export const optNumber = (input: unknown, key: string): number | undefined => {
  const v = rec(input)[key]
  return typeof v === 'number' ? v : undefined
}
export const optBool = (input: unknown, key: string): boolean | undefined => {
  const v = rec(input)[key]
  return typeof v === 'boolean' ? v : undefined
}
export const optObject = (input: unknown, key: string): Record<string, unknown> | undefined => {
  const v = rec(input)[key]
  return v && typeof v === 'object' && !Array.isArray(v) ? (v as Record<string, unknown>) : undefined
}
